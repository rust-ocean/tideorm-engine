use crate::{
    ActiveModelTrait, ColumnTrait, Delete, DeleteMany, DeleteOne, FromQueryResult, Identity,
    Insert, InsertMany, ModelTrait, PrimaryKeyArity, PrimaryKeyToColumn, PrimaryKeyTrait,
    QueryFilter, Select, Update, UpdateMany, UpdateOne, ValidatedDeleteOne,
};
use sql_builder::{Iden, IntoIden, IntoTableRef, IntoValueTuple, TableRef};
use std::fmt::Debug;

/// An enum that lists its variants: an entity's columns and primary keys, and
/// an active enum's values. `#[derive(EnumIter)]` implements it.
pub trait Iterable: Sized + 'static {
    /// Every variant, in declaration order.
    const ALL: &'static [Self];

    /// Every variant, in declaration order.
    fn iter() -> std::iter::Cloned<std::slice::Iter<'static, Self>>
    where
        Self: Clone,
    {
        Self::ALL.iter().cloned()
    }
}

/// An identifier (table or column name) that can be borrowed as a `&'static str`.
pub trait IdenStatic: Iden + Copy + Debug + Send + Sync + 'static {
    /// The static SQL identifier this value represents.
    fn as_str(&self) -> &'static str;
}

/// Names the SQL table backing an [`Entity`](EntityTrait), and its optional
/// schema.
///
/// One of the building blocks of [`EntityTrait`]; TideORM's model derive
/// implements it.
pub trait EntityName: IdenStatic + Default {
    /// Schema name this table lives in (PostgreSQL / SQL Server). Returns
    /// `None` when the table lives in the connection's default schema.
    fn schema_name(&self) -> Option<&str> {
        None
    }

    /// SQL name of the table.
    fn table_name(&self) -> &'static str;

    /// [`TableRef`] for this entity, qualified with [`schema_name`](Self::schema_name)
    /// if one is set.
    fn table_ref(&self) -> TableRef {
        match self.schema_name() {
            Some(schema) => (schema.to_owned(), self.into_iden()).into_table_ref(),
            None => self.into_table_ref(),
        }
    }
}

/// The contract every entity implements — a static description of a
/// table plus the CRUD entry points used to query it.
///
/// Normally generated by TideORM's model derive for its
/// [`Model`](ModelTrait) struct.
///
/// Each implementor exposes:
///
/// - **`Model`** / **`ActiveModel`** — the row struct and its editable
///   counterpart (see [`ModelTrait`], [`ActiveModelTrait`]).
/// - **`Column`** — strongly-typed enum of the table's columns
///   (see [`ColumnTrait`]).
/// - **`PrimaryKey`** — enum identifying the primary key column(s)
///   (see [`PrimaryKeyTrait`]).
///
/// And entry points for queries: [`find`](Self::find), [`find_by_id`](Self::find_by_id),
/// [`insert`](Self::insert), [`insert_many`](Self::insert_many),
/// [`update`](Self::update), [`update_many`](Self::update_many),
/// [`delete`](Self::delete), [`delete_many`](Self::delete_many),
/// [`delete_by_id`](Self::delete_by_id).
pub trait EntityTrait: EntityName {
    #[allow(missing_docs)]
    type Model: ModelTrait<Entity = Self> + FromQueryResult;

    #[allow(missing_docs)]
    type ActiveModel: ActiveModelTrait<Entity = Self>;

    #[allow(missing_docs)]
    type Column: ColumnTrait;

    #[allow(missing_docs)]
    type PrimaryKey: PrimaryKeyTrait + PrimaryKeyToColumn<Column = Self::Column>;

    /// Construct select statement to find one / all models
    ///
    /// - To select columns, join tables and group by expressions, see [`QuerySelect`](crate::query::QuerySelect)
    /// - To apply where conditions / filters, see [`QueryFilter`](crate::query::QueryFilter)
    /// - To apply order by expressions, see [`QueryOrder`](crate::query::QueryOrder)
    fn find() -> Select<Self> {
        Select::new()
    }

    /// Find a model by primary key
    ///
    /// Find by composite key
    fn find_by_id<T>(values: T) -> Select<Self>
    where
        T: Into<<Self::PrimaryKey as PrimaryKeyTrait>::ValueType>,
    {
        let mut select = Self::find();
        let mut keys = Self::PrimaryKey::iter();
        for v in values.into().into_value_tuple() {
            if let Some(key) = keys.next() {
                let col = key.into_column();
                select = select.filter(col.eq(v));
            } else {
                unreachable!("primary key arity mismatch");
            }
        }
        select
    }

    /// Get primary key as Identity
    fn primary_key_identity() -> Identity {
        let mut cols = Self::PrimaryKey::iter();
        macro_rules! next {
            () => {
                cols.next()
                    .expect("Already checked arity")
                    .into_column()
                    .as_column_ref()
                    .1
            };
        }
        match <<Self::PrimaryKey as PrimaryKeyTrait>::ValueType as PrimaryKeyArity>::ARITY {
            1 => {
                let s1 = next!();
                Identity::Unary(s1)
            }
            2 => {
                let s1 = next!();
                let s2 = next!();
                Identity::Binary(s1, s2)
            }
            3 => {
                let s1 = next!();
                let s2 = next!();
                let s3 = next!();
                Identity::Ternary(s1, s2, s3)
            }
            len => {
                let mut vec = Vec::with_capacity(len);
                for _ in 0..len {
                    let s = next!();
                    vec.push(s);
                }
                Identity::Many(vec)
            }
        }
    }

    /// Insert a model into database
    fn insert<A>(model: A) -> Insert<A>
    where
        A: ActiveModelTrait<Entity = Self>,
    {
        Insert::one(model)
    }

    /// Insert many models into database
    ///
    /// When the active models set different columns, the missing ones are filled with
    /// null, which suits only nullable columns.
    fn insert_many<A, I>(models: I) -> InsertMany<A>
    where
        A: ActiveModelTrait<Entity = Self>,
        I: IntoIterator<Item = A>,
    {
        InsertMany::many(models)
    }

    /// Update a model in database
    ///
    /// - To apply where conditions / filters, see [`QueryFilter`](crate::query::QueryFilter)
    fn update<A>(model: A) -> UpdateOne<A>
    where
        A: ActiveModelTrait<Entity = Self>,
    {
        Update::one(model)
    }

    /// Update many models in database
    ///
    /// - To apply where conditions / filters, see [`QueryFilter`](crate::query::QueryFilter)
    fn update_many() -> UpdateMany<Self> {
        Update::many(Self::default())
    }

    /// Delete a model from database
    ///
    /// - To apply where conditions / filters, see [`QueryFilter`](crate::query::QueryFilter)
    fn delete<A>(model: A) -> DeleteOne<Self>
    where
        A: ActiveModelTrait<Entity = Self>,
    {
        Delete::one(model)
    }

    /// Delete many models from database
    ///
    /// - To apply where conditions / filters, see [`QueryFilter`](crate::query::QueryFilter)
    fn delete_many() -> DeleteMany<Self> {
        Delete::many(Self::default())
    }

    /// Delete a model based on primary key
    ///
    /// Delete by composite key
    fn delete_by_id<T>(values: T) -> ValidatedDeleteOne<Self>
    where
        T: Into<<Self::PrimaryKey as PrimaryKeyTrait>::ValueType>,
    {
        let mut am = Self::ActiveModel::default();
        let mut keys = Self::PrimaryKey::iter();
        for v in values.into().into_value_tuple() {
            if let Some(key) = keys.next() {
                let col = key.into_column();
                am.set(col, v);
            } else {
                unreachable!("primary key arity mismatch");
            }
        }
        Delete::one(am).validate().expect("Must be valid")
    }
}
